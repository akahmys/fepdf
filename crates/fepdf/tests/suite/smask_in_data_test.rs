//! `/SMaskInData` (8.9.5.2, Table 89): the transparency a JPX image carries in its own
//! data.
//!
//! `/JPXDecode` is the only filter whose image may hold its own soft mask, and this
//! engine dropped the fourth channel unconditionally — the behaviour `/SMaskInData 0`
//! asks for, applied to files asking for 1 and 2 as well, so a transparent image was
//! drawn opaque and nothing said so.
//!
//! **The fixtures were encoded by OpenJPEG, not by the decoder under test** — the rule
//! `make_scan_fixtures.rs` follows, for the reason it gives: a codec checked only against
//! a fixture its own author wrote is checked against an opinion. Neither corpus carries a
//! `/SMaskInData` at all, and its one JPX image is plain RGB, so there was nothing here
//! to check against. Regenerate with Pillow over OpenJPEG:
//!
//! ```text
//! img = Image.new("RGBA", (8, 8)); ...
//! img.save(buf, format="JPEG2000", irreversible=False, quality_mode="lossless")
//! ```
//!
//! The codestreams say so themselves: each carries a comment marker reading
//! "Created by OpenJPEG version 2.5.3".

